// Run only against scripts/browser_validation_stack.py with BROWSER_SITE_LAYOUT=pharma.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = 'http://127.0.0.1:19300';
const out = path.resolve(process.env.BROWSER_EVIDENCE_DIR || 'docs/validation/ui-overhaul');
fs.mkdirSync(out, { recursive: true });
const report = { scope: 'Real isolated simulator/backend; no model calls', checks: [], errors: [] };
const wait = ms => new Promise(r => setTimeout(r, ms));
async function until(fn, message, timeout=45000) {
  const end = Date.now()+timeout;
  while (Date.now()<end) { if (await fn()) return; await wait(500); }
  throw new Error(message);
}
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({ viewport:{width:1440,height:1050}, reducedMotion:'reduce' });
  const page = await context.newPage();
  page.on('pageerror', e => report.errors.push(e.message));
  const api = async p => (await context.request.get(base+'/api'+p)).json();
  try {
    await page.goto(base);
    await page.getByRole('heading',{name:/Intelligence that acts/}).waitFor();
    await page.screenshot({path:path.join(out,'landing-desktop.png'),fullPage:true});
    await page.getByRole('link',{name:/Open the app/}).first().waitFor();
    await page.goto(base+'/mission-control');
    await page.locator('.sa-live-state').filter({hasText:'Live simulation'}).waitFor({timeout:60000});
    await page.getByRole('heading',{name:'Meridian Life Sciences'}).waitFor();
    await page.getByRole('button',{name:'Launch mission',exact:true}).waitFor();
    assert.equal(await page.locator('.sa-fleet-card').count(),3);
    await page.waitForTimeout(2000);
    await page.locator('.sa-live-state').filter({hasText:'Live simulation'}).waitFor({timeout:45000});
    await page.screenshot({path:path.join(out,'mission-control-3d.png'),fullPage:true});
    assert.ok(await page.locator('canvas').count(), 'New 3D facility renders');
    await page.getByRole('button',{name:'Follow robot',exact:true}).click();
    await page.waitForTimeout(800);
    await page.locator('.sa-live-state').filter({hasText:'Live simulation'}).waitFor({timeout:45000});
    await page.screenshot({path:path.join(out,'facility-follow.png'),fullPage:true});
    await page.getByRole('button',{name:'Robot eye',exact:true}).click();
    await page.waitForTimeout(800);
    await page.locator('.sa-live-state').filter({hasText:'Live simulation'}).waitFor({timeout:45000});
    await page.screenshot({path:path.join(out,'facility-robot-eye.png'),fullPage:true});
    await page.getByRole('button',{name:'Overview',exact:true}).click();
    report.checks.push('Perspective overview, robot follow and robot-eye cameras retain the new dashboard');
    report.checks.push('Original landing restored with its app link; Mission Control loads the real pharma world and fleet');
    await page.getByRole('button',{name:'Floor plan',exact:true}).click();
    await page.getByRole('button',{name:'Select robot-2',exact:true}).focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.getByLabel('Assigned robot').inputValue(),'robot-2');
    await page.getByLabel('Assigned robot').selectOption('robot-1');
    await page.getByRole('button',{name:'Operator access',exact:true}).click();
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.getByLabel('Username',{exact:true}).evaluate(e=>e===document.activeElement),true);
    await page.screenshot({path:path.join(out,'operator-access.png'),fullPage:true});
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(),0);
    report.checks.push('Keyboard robot selection and accessible operator dialog work');
    await page.getByLabel('Destination').selectOption('P-01');
    await page.getByRole('button',{name:'Launch mission',exact:true}).click();
    await page.getByRole('button',{name:'Pause',exact:true}).waitFor({timeout:45000});
    const runs = await api('/runs');
    const run = runs.find(r=>['running','planning','paused'].includes(r.status));
    assert.ok(run,'Backend has the launched mission');
    await until(async()=> (await api(`/runs/${run.id}/events?latest=true&limit=80`)).some(e=>e.type==='AUTHORITY'&&e.payload?.event==='permit_used'),'No controller admission');
    await page.getByText('Controller admission recorded',{exact:true}).waitFor({timeout:30000});
    const previousWorld = await api('/sim/world');
    await page.getByRole('tab',{name:'Try a scenario',exact:true}).click();
    await page.locator('.sa-scenario-grid button').filter({hasText:'The route changes'}).click();
    await until(async()=> (await api('/sim/world')).map_version !== previousWorld.map_version,'Obstacle did not change real environment');
    await until(async()=> (await api(`/runs/${run.id}/events?latest=true&limit=80`)).some(e=>e.type==='ENVIRONMENT_CHANGE'),'Environment change missing from mission evidence');
    await page.locator('.sa-scenario-grid button').filter({hasText:'Clear the route'}).click();
    await page.getByRole('tab',{name:'What happened',exact:true}).click();
    report.checks.push('Scenario lab changes real world geometry and records environment revalidation');
    await page.getByRole('button',{name:'Pause',exact:true}).click();
    await page.getByRole('button',{name:'Resume',exact:true}).waitFor();
    assert.equal((await api('/runs')).find(r=>r.id===run.id).status,'paused');
    report.checks.push('Mission creation, controller admission evidence and pause update real backend state');
    await page.screenshot({path:path.join(out,'mission-evidence.png'),fullPage:true});
    await page.getByRole('button',{name:'New mission',exact:true}).click();
    await page.getByRole('button',{name:'Launch mission',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Launch mission',exact:true}).isDisabled(),true);
    await page.getByLabel('Assigned robot').selectOption('robot-2');
    assert.equal(await page.getByRole('button',{name:'Launch mission',exact:true}).isEnabled(),true);
    report.checks.push('New mission opens composer; busy robot blocked and second robot selectable');
    await page.getByRole('button',{name:'Stop fleet',exact:true}).click();
    await page.getByText('Fleet stop confirmed by the controller.',{exact:true}).waitFor();
    await until(async()=> (await api('/authority/status')).kill_locks.some(l=>l.scope==='global'),'No global stop lock');
    await page.getByRole('button',{name:'Release stop (operator)',exact:true}).waitFor({timeout:10000});
    await page.getByRole('button',{name:'Release stop (operator)',exact:true}).click();
    await until(async()=> !(await api('/authority/status')).kill_locks.length,'Stop lock not released');
    assert.equal((await api('/runs')).find(r=>r.id===run.id).status,'paused');
    report.checks.push('Persistent stop confirms controller stop; release does not resume paused mission');
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
    await page.screenshot({path:path.join(out,'mission-control-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile horizontal overflow');
    await page.getByRole('button',{name:'Operator access',exact:true}).click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Open navigation',exact:true}).click();
    await page.getByRole('link',{name:'Mission history',exact:true}).waitFor();
    await page.getByRole('button',{name:'Close navigation',exact:true}).click();
    report.checks.push('Mobile has no horizontal overflow; navigation, operator access and stop remain available');
    await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
    await page.route('**/api/**',route=>route.abort('failed'));
    await page.waitForTimeout(6500);
    await page.locator('.sa-live-state').filter({hasText:'Connection interrupted'}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Launch mission',exact:true}).isDisabled(),true);
    await page.getByText('Last received positions · not live',{exact:true}).waitFor();
    await page.screenshot({path:path.join(out,'disconnected-mobile.png'),fullPage:true});
    report.checks.push('Lost connection marks positions stale and disables launching');
    await page.unroute('**/api/**');
    const fallback = await context.newPage();
    await fallback.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(String(type).includes('webgl'))return null;return get.call(this,type,...args);};});
    await fallback.goto(base+'/mission-control');
    await fallback.getByText('3D unavailable · floor plan and controls remain usable',{exact:true}).waitFor({timeout:45000});
    assert.ok(await fallback.locator('.sa-facility-map').count());
    await fallback.screenshot({path:path.join(out,'webgl-fallback.png'),fullPage:true});
    report.checks.push('Unavailable WebGL falls back to real floor plan while keeping controls');
    await fallback.close();
    assert.deepEqual(report.errors,[],'Unexpected page errors');
    report.passed = true;
  } finally {
    fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2)+'\n');
    await browser.close();
  }
  console.log(JSON.stringify(report,null,2));
})().catch(e=>{console.error(e);process.exitCode=1;});
